import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const home=readFileSync('public/index.html','utf8');
const fast=readFileSync('public/index-fast.html','utf8');
const route=readFileSync('public/am-route.js','utf8');
const routeCSS=readFileSync('public/am-route.css','utf8');
const collection=readFileSync('public/am-collection.js','utf8');
const collectionCSS=readFileSync('public/am-collection.css','utf8');
assert.equal(home,fast,'Both homepages must match');
assert.ok(home.includes('id="supply-journey"'),'Missing new story section');
assert.equal((home.match(/data-route-step=/g)||[]).length,3);
assert.equal((home.match(/data-route-shot=/g)||[]).length,3);
for(const s of ['am-route.css','am-route.js','data-offer-prev','data-offer-next','data-offer-position','id="quote-form"','id="collections"','id="immersive"'])assert.ok(home.includes(s),'Missing '+s);
for(const s of ['requestAnimationFrame','getBoundingClientRect','is-active','IntersectionObserver','prefers-reduced-motion'])assert.ok(route.includes(s),'Missing '+s);
assert.ok(routeCSS.includes('position:sticky')&&routeCSS.includes('@media(max-width:850px)'));
for(const s of ['data-offer-prev','data-offer-next','ArrowLeft','ArrowRight','am-tilt-x','am-tilt-y','requestAnimationFrame'])assert.ok(collection.includes(s),'Missing '+s);
assert.ok(collectionCSS.includes('am-offer-dialog.is-switching')&&collectionCSS.includes('am-offer-navigator'));
assert.equal((home.match(/data-offer="/g)||[]).length,10);
assert.ok(!/<video\b/i.test(home)&&!route.includes('.mp4')&&!collection.includes('.mp4'));
console.log('PASS MotionSites photographic scroll-story and luxury service collection');