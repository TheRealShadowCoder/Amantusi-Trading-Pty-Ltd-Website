import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(p,'utf8');
const home=read('public/index.html'),fast=read('public/index-fast.html');
const collection=read('public/am-collection.js'),css=read('public/am-collection.css');
const showcase=read('public/showcase-3d.js'),routeCSS=read('public/am-route.css');
const quote=read('public/quote-enhancements.js'),app=read('public/app-fast.js');
const wr=JSON.parse(read('wrangler.jsonc'));
assert.equal(home,fast,'Both homepage variants must match');
for(const value of ['id="collections"','id="supply-journey"','id="capabilities"','id="immersive"','id="quote-form"'])assert.ok(home.includes(value),'Missing '+value);
const idx=id=>home.indexOf('id="'+id+'"');
assert.ok(idx('about')<idx('collections')&&idx('collections')<idx('supply-journey')&&idx('supply-journey')<idx('capabilities'),'Primary service browsing should follow the hero/introduction');
assert.ok(home.includes('<details class="am-showroom-disclosure">')&&home.includes('<summary class="am-showroom-summary">'),'Detailed secondary showroom must be optional');
assert.ok(showcase.includes("optionalStudio.open")&&showcase.includes("optionalStudio?.addEventListener('toggle'"),'Optional showroom rendering must honor collapsed state');
assert.ok(collection.includes('preserveFocus=false')&&collection.includes('preserveFocus:true'),'Keyboard focus must persist across service changes');
assert.ok(css.includes('min-height:46px')&&css.includes('min-width:104px'),'Service navigator must be touch friendly');
assert.ok(routeCSS.includes('min-height:clamp(380px,64svh,640px)'),'Long scroll-story must be condensed');
assert.ok(home.includes('aria-label="Quotation process"')&&home.includes('Specification-led quotations'),'Visible honest RFQ trust guidance required');
assert.ok(quote.includes("status.focus({preventScroll:true})")&&app.includes("status.focus({preventScroll:true})"),'Form errors must receive keyboard focus');
const url='https://amantusi-trading-pty-ltd-website.dolomite-computer.workers.dev/';
assert.ok(home.includes('rel="canonical" href="'+url+'"')&&home.includes('property="og:image"')&&home.includes('application/ld+json'),'Canonical, OG image and structured business data must exist');
const json=home.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/);
assert.ok(json,'Business JSON-LD missing');
const business=JSON.parse(json[1]);
assert.equal(business.name,'Amantusi Trading (Pty) Ltd');
assert.equal(business['@type'],'Organization');
assert.equal(business.url,url);
assert.ok(!/<video\b/i.test(home),'No video may return');
assert.equal(wr.observability.enabled,false,'Cloudflare observability must remain disabled');
assert.equal(wr.logpush,false,'Cloudflare logpush must remain disabled');
assert.equal(wr.vars.GCP_OVERFLOW_ENABLED,'false','External overflow remains disabled');
assert.ok(!home.includes('€249')&&!home.includes('Add to Bag'),'No fabricated ecommerce inventory');
console.log('PASS UI UX audit upgrades: service priority, optional studio, preserved focus, accessible RFQ errors, SEO and Free-tier guarantees');
